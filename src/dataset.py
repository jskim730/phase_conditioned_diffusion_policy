import os
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset
from typing import Sequence


# =====================================================================
# Normalization helpers
# =====================================================================

def normalize_obs(obs: np.ndarray, obs_mean: np.ndarray, obs_std: np.ndarray) -> np.ndarray:
    """Per-dim z-score: (obs - μ) / σ."""
    return (obs - obs_mean) / obs_std


def unnormalize_obs(obs_n: np.ndarray, obs_mean: np.ndarray, obs_std: np.ndarray) -> np.ndarray:
    return obs_n * obs_std + obs_mean


def normalize_action(act: np.ndarray, act_min: np.ndarray, act_range: np.ndarray) -> np.ndarray:
    """Per-dim min-max → [-1, 1]."""
    return 2.0 * (act - act_min) / act_range - 1.0


def unnormalize_action(act_n, act_min, act_range):
    """[-1, 1] → raw. numpy/torch 모두 지원."""
    if isinstance(act_n, np.ndarray):
        return (act_n + 1.0) / 2.0 * act_range + act_min
    # torch tensor
    if not torch.is_tensor(act_min):
        act_min = torch.from_numpy(act_min).float().to(act_n.device)
    if not torch.is_tensor(act_range):
        act_range = torch.from_numpy(act_range).float().to(act_n.device)
    return (act_n + 1.0) / 2.0 * act_range + act_min


# =====================================================================
# Dataset
# =====================================================================

class AntPhaseDataset(Dataset):
    """Chunked dataset for Phase-Conditioned Diffusion Policy.

    각 sample은 (obs window, action chunk, phase chunk).
    Phase는 raw φ ∈ [0, 2π)로 반환하고 모델 안에서 (cos φ, sin φ)로 인코딩.
    Vanilla DP 단계에서는 phase가 반환되지만 무시됨. 미리 포함시켜
    Phase-Conditioned 단계로 넘어갈 때 Dataset 코드 변경 0.

    Indexing 규칙:
        episode 내 시점 t에 대해
            obs[t - obs_horizon + 1 : t + 1]   → obs window
            action[t : t + pred_horizon]       → action chunk
            phase[t : t + pred_horizon]        → phase chunk
        Valid t: [obs_horizon - 1, episode_length - pred_horizon]
    """

    def __init__(
        self,
        obs_data: np.ndarray,
        act_data: np.ndarray,
        phase_data: np.ndarray,
        ep_lengths: np.ndarray,
        episode_indices: Sequence[int],
        obs_horizon: int,
        pred_horizon: int,
        obs_mean: np.ndarray,
        obs_std: np.ndarray,
        act_min: np.ndarray,
        act_range: np.ndarray,
        verbose: bool = True,
    ):
        self.obs_data     = obs_data
        self.act_data     = act_data
        self.phase_data   = phase_data
        self.obs_horizon  = obs_horizon
        self.pred_horizon = pred_horizon

        # Normalization stats
        self.obs_mean  = obs_mean.astype(np.float32)
        self.obs_std   = obs_std.astype(np.float32)
        self.act_min   = act_min.astype(np.float32)
        self.act_range = act_range.astype(np.float32)

        # Build flat index of valid (ep_idx, t)
        self.index = []
        for ep_idx in episode_indices:
            L = int(ep_lengths[ep_idx])
            t_min = obs_horizon - 1
            t_max = L - pred_horizon
            for t in range(t_min, t_max + 1):
                self.index.append((int(ep_idx), int(t)))

        if verbose:
            print(f"  AntPhaseDataset: {len(episode_indices)} episodes "
                  f"→ {len(self.index)} chunks")

    def __len__(self):
        return len(self.index)

    def __getitem__(self, idx):
        ep_idx, t = self.index[idx]
        oh, ph_h = self.obs_horizon, self.pred_horizon

        obs = self.obs_data[ep_idx, t - oh + 1 : t + 1]   # (oh, obs_dim)
        act = self.act_data[ep_idx, t : t + ph_h]          # (ph_h, act_dim)
        ph  = self.phase_data[ep_idx, t : t + ph_h]        # (ph_h,)

        obs_n = (obs - self.obs_mean) / self.obs_std
        act_n = 2.0 * (act - self.act_min) / self.act_range - 1.0

        return {
            'obs':    torch.from_numpy(obs_n.astype(np.float32)),
            'action': torch.from_numpy(act_n.astype(np.float32)),
            'phase':  torch.from_numpy(ph.astype(np.float32)),
        }


