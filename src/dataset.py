def compute_diff_norm_per_phase(
    obs_data: np.ndarray,
    act_data: np.ndarray,
    phase_data: np.ndarray,
    ep_lengths: np.ndarray,
    episode_indices,
    pred_horizon: int,
    obs_horizon: int,
    act_min: np.ndarray,
    act_range: np.ndarray,
) -> dict:
    """학습 데이터에서 'action diff norm / phase diff' 비율 측정.

    Phase Consistency Sampling의 cost function에서 사용:
      C = || ||a_{t+1} - a_t||₂ - K · |φ_{t+1} - φ_t| ||²

    여기서 K = mean(action_diff_norm / phase_diff) (학습 데이터 기반).

    Action은 sampling 함수 내부에서 [-1, 1] normalize된 chunk를 다룸.
    그래서 K도 normalize된 action 기준으로 측정.
    """
    diff_ratios = []

    for ep_idx in episode_indices:
        L = int(ep_lengths[ep_idx])
        t_min = obs_horizon - 1
        t_max = L - pred_horizon
        if t_max < t_min:
            continue

        # Episode 내 모든 valid chunk
        for t in range(t_min, t_max + 1):
            act_chunk = act_data[ep_idx, t : t + pred_horizon]    # (PH, A)
            ph_chunk  = phase_data[ep_idx, t : t + pred_horizon]  # (PH,)

            # Normalize action (sampling time과 일치)
            act_n = 2.0 * (act_chunk - act_min) / act_range - 1.0  # (PH, A)

            # Phase diff — wraparound 처리 (unwrap 후 diff)
            ph_unwrap = np.unwrap(ph_chunk)
            phase_diff = np.abs(np.diff(ph_unwrap))                # (PH-1,)

            # Action diff norm (L2 over action dims)
            act_diff = np.diff(act_n, axis=0)                       # (PH-1, A)
            act_diff_norm = np.linalg.norm(act_diff, axis=-1)      # (PH-1,)

            # Element-wise 비율 (phase_diff 0인 step 제외)
            mask = phase_diff > 1e-6
            if mask.any():
                ratios = act_diff_norm[mask] / phase_diff[mask]
                diff_ratios.extend(ratios.tolist())

    diff_ratios = np.array(diff_ratios, dtype=np.float32)
    stats = {
        'mean':   float(diff_ratios.mean()),
        'median': float(np.median(diff_ratios)),
        'std':    float(diff_ratios.std()),
        'p25':    float(np.percentile(diff_ratios,  25)),
        'p75':    float(np.percentile(diff_ratios,  75)),
        'n':      int(len(diff_ratios)),
    }
    return stats

def compute_phase_dependent_K(
    obs_data: np.ndarray,
    act_data: np.ndarray,
    phase_data: np.ndarray,
    ep_lengths: np.ndarray,
    episode_indices,
    pred_horizon: int,
    obs_horizon: int,
    act_min: np.ndarray,
    act_range: np.ndarray,
    n_bins: int = 16,
) -> dict:
    """Phase-position dependent K(φ) — n_bins lookup table.

    Boards이 phase에 따라 ratio가 크게 변동하므로 (stance vs swing),
    phase 위치별로 다른 K 사용. 각 chunk의 (Δφ_t, ratio_t) pair를 step의
    시작 phase의 bin으로 분류 → bin별 median ratio.

    Returns dict:
        K_table:    (n_bins,) — bin별 median ratio
        bin_edges:  (n_bins+1,) — [0, 2π/N, ..., 2π]
        bin_counts: (n_bins,) — bin별 sample 수
        n_bins:     int
    """
    bin_ratios = [[] for _ in range(n_bins)]

    for ep_idx in episode_indices:
        L = int(ep_lengths[ep_idx])
        t_min = obs_horizon - 1
        t_max = L - pred_horizon
        if t_max < t_min:
            continue

        for t in range(t_min, t_max + 1):
            act_chunk = act_data[ep_idx, t : t + pred_horizon]
            ph_chunk  = phase_data[ep_idx, t : t + pred_horizon]

            act_n = 2.0 * (act_chunk - act_min) / act_range - 1.0

            ph_unwrap = np.unwrap(ph_chunk)
            phase_diff = np.abs(np.diff(ph_unwrap))
            act_diff = np.diff(act_n, axis=0)
            act_diff_norm = np.linalg.norm(act_diff, axis=-1)

            # Step의 시작 phase 기준으로 bin 분류 (mod 2π)
            ph_start_per_step = ph_chunk[:-1] % (2 * np.pi)

            for i in range(len(phase_diff)):
                if phase_diff[i] > 1e-6:
                    ratio = act_diff_norm[i] / phase_diff[i]
                    bin_idx = int(ph_start_per_step[i] / (2 * np.pi) * n_bins)
                    bin_idx = max(0, min(bin_idx, n_bins - 1))
                    bin_ratios[bin_idx].append(float(ratio))

    K_table = np.zeros(n_bins, dtype=np.float32)
    bin_counts = np.zeros(n_bins, dtype=np.int32)
    for b in range(n_bins):
        if bin_ratios[b]:
            K_table[b] = float(np.median(bin_ratios[b]))
            bin_counts[b] = len(bin_ratios[b])
        else:
            K_table[b] = 1.0  # fallback for empty bin

    bin_edges = np.linspace(0, 2 * np.pi, n_bins + 1, dtype=np.float32)
    return {
        'K_table':    K_table,
        'bin_edges':  bin_edges,
        'bin_counts': bin_counts,
        'n_bins':     n_bins,
    }