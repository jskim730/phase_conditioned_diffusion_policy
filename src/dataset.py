def _resolve_data_dir(data_dir: str | os.PathLike[str] | None = None) -> Path:
    """Return the directory containing demo and normalization artifacts."""
    if data_dir is None:
        from paths import DATA_DIR
        return DATA_DIR

    candidate = Path(data_dir).expanduser().resolve()
    direct_demos = candidate / 'demos_ant_planC.npz'
    direct_norm = candidate / 'norm_stats.npz'
    nested = candidate / 'data'

    if not (direct_demos.exists() and direct_norm.exists()) and nested.exists():
        return nested
    return candidate


def load_project_data(data_dir: str | os.PathLike[str] | None = None):
    """Load demos + norm_stats from the artifact data directory.

    ``data_dir`` defaults to ``paths.DATA_DIR``.  Passing an artifact root from
    older notebooks is also supported: when files are not found directly under
    that path but ``<root>/data`` exists, the nested data directory is used.

    Returns dict with all variables Step 2+ notebooks expect.
    """
    data_dir = _resolve_data_dir(data_dir)
    demos_path = data_dir / 'demos_ant_planC.npz'
    norm_path = data_dir / 'norm_stats.npz'
    assert demos_path.exists(), f"파일 없음: {demos_path}"
    assert norm_path.exists(),  f"파일 없음: {norm_path}"

    demos = np.load(demos_path)
    norm  = np.load(norm_path)

    return {
        # Raw demo arrays
        'obs_data':    demos['observations'],
        'act_data':    demos['actions'],
        'phase_data':  demos['phases'],
        'ep_lengths':  demos['episode_lengths'],
        # Normalization stats
        'obs_mean':  norm['obs_mean'],
        'obs_std':   norm['obs_std'],
        'act_min':   norm['act_min'],
        'act_max':   norm['act_max'],
        'act_range': norm['act_range'],
        # Hyperparams (consistency 보장)
        'OBS_HORIZON':    int(norm['obs_horizon']),
        'PRED_HORIZON':   int(norm['pred_horizon']),
        'ACTION_HORIZON': int(norm['action_horizon']),
        'OBS_DIM':        int(norm['obs_dim']),
        'ACT_DIM':        int(norm['act_dim']),
        # Split
        'train_eps': norm['train_eps'],
        'val_eps':   norm['val_eps'],
        'seed':      int(norm['seed']),
        # Frequency window metadata
        'freq_window_mean': float(norm['freq_window_mean']),
        'freq_window_std':  float(norm['freq_window_std']),
        'freq_window_min':  float(norm['freq_window_min']),
        'freq_window_max':  float(norm['freq_window_max']),
    }


def build_loaders(data: dict, batch_size: int = 256, num_workers: int = 2,
                  verbose: bool = True):
    """load_project_data 결과로부터 train/val DataLoader 생성."""
    from torch.utils.data import DataLoader

    common = dict(
        obs_data=data['obs_data'],
        act_data=data['act_data'],
        phase_data=data['phase_data'],
        ep_lengths=data['ep_lengths'],
        obs_horizon=data['OBS_HORIZON'],
        pred_horizon=data['PRED_HORIZON'],
        obs_mean=data['obs_mean'],
        obs_std=data['obs_std'],
        act_min=data['act_min'],
        act_range=data['act_range'],
        verbose=verbose,
    )

    if verbose:
        print("Train dataset:")
    train_ds = AntPhaseDataset(episode_indices=data['train_eps'], **common)

    if verbose:
        print("Val dataset:")
    val_ds = AntPhaseDataset(episode_indices=data['val_eps'], **common)

    train_loader = DataLoader(
        train_ds, batch_size=batch_size, shuffle=True,
        num_workers=num_workers, pin_memory=True, drop_last=True,
    )
    val_loader = DataLoader(
        val_ds, batch_size=batch_size, shuffle=False,
        num_workers=num_workers, pin_memory=True, drop_last=False,
    )

    if verbose:
        print(f"  Train batches/epoch: {len(train_loader)}")
        print(f"  Val batches/epoch:   {len(val_loader)}")

    return train_ds, val_ds, train_loader, val_loader
